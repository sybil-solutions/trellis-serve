// Host-side scatter copy for the expert store loader: entry j = (src_off, dst_addr, rows, row_bytes, dst_stride) copies
// `rows` rows of `row_bytes` from src + src_off (contiguous) to dst_addr + r * dst_stride. Split over `threads` std::threads;
// the binding releases the GIL, so the reader thread keeps streaming the next group meanwhile.
#include <thread>
#include <cstring>
void host_scatter_copy(const at::Tensor& src, const at::Tensor& entries, int64_t threads) {
  TORCH_CHECK(src.device().is_cpu() && src.dtype() == at::kByte && src.is_contiguous());
  TORCH_CHECK(entries.device().is_cpu() && entries.dtype() == at::kLong && entries.dim() == 2 && entries.size(1) == 5 &&
              entries.is_contiguous());
  const uint8_t* s = src.data_ptr<uint8_t>();
  const int64_t n = entries.size(0), nbytes = src.numel();
  const int64_t* E = entries.data_ptr<int64_t>();
  for (int64_t j = 0; j < n; j++)
    TORCH_CHECK(E[5 * j] >= 0 && E[5 * j] + E[5 * j + 2] * E[5 * j + 3] <= nbytes, "host_scatter_copy: source out of range");
  auto work = [&](int64_t a, int64_t b) {
    for (int64_t j = a; j < b; j++) {
      const int64_t so = E[5 * j], rows = E[5 * j + 2], rb = E[5 * j + 3], ds = E[5 * j + 4];
      uint8_t* d = reinterpret_cast<uint8_t*>(E[5 * j + 1]);
      if (ds == rb) std::memcpy(d, s + so, rows * rb);
      else for (int64_t r = 0; r < rows; r++) std::memcpy(d + r * ds, s + so + r * rb, rb);
    }
  };
  const int64_t T = std::max<int64_t>(1, std::min<int64_t>(threads, n));
  std::vector<std::thread> pool;
  for (int64_t t = 0; t < T; t++) pool.emplace_back(work, n * t / T, n * (t + 1) / T);
  for (auto& th : pool) th.join();
}

// The same host memory seen as a CUDA tensor (same sizes / strides / dtype, UVA device address): torch ops on it read
// host memory from the SMs over PCIe (zero-copy). Keeps the host tensor alive.
at::Tensor host_as_cuda(const at::Tensor& t, int64_t device) {
  void* d = nullptr;
  cudaError_t err = cudaHostGetDevicePointer(&d, t.data_ptr(), 0);
  TORCH_CHECK(err == cudaSuccess, "cudaHostGetDevicePointer failed (memory not pinned+mapped?): ", cudaGetErrorString(err));
  at::Tensor keep = t;
  return at::from_blob(d, t.sizes(), t.strides(), [keep](void*) {},
                       at::TensorOptions().dtype(t.dtype()).device(at::Device(at::kCUDA, (int)device)));
}

// ---------------------------------------------------------------------------------------------------------------
// Decode-sized routing for mixed-K layers: ONE launch produces, for every K class, the (sorted_token_ids, expert_ids,
// num_tokens_post_padded) triple vLLM's moe_align_block_size would produce with that class's expert_map and
// ignore_invalid_experts=True (padding slots = numel, padding blocks = -1, local expert ids, per-expert counts padded
// to the class's block size, experts in ascending global order). vLLM's kernel is generic (grids, cub scans over 256
// experts, a separate fill launch) and much slower per class at decode sizes; this fused launch does both classes at once.
// One block of 1024 threads; slots <= TRELLIS_ALIGN_MAX_SLOTS, experts <= 1024, classes <= 2.
#include <cub/cub.cuh>
#define TRELLIS_ALIGN_MAX_SLOTS 4096
#define TRELLIS_ALIGN_MAX_E 1024

__global__ __launch_bounds__(1024)
void trellis_moe_align_decode_kernel(const int* __restrict__ topk_ids, int slots, int num_experts, int num_classes,
                                    const int* __restrict__ map0, const int* __restrict__ map1, int block0, int block1,
                                    int* __restrict__ sorted0, int* __restrict__ sorted1, int cap0, int cap1,
                                    int* __restrict__ eids0, int* __restrict__ eids1, int mblk0, int mblk1,
                                    int* __restrict__ post0, int* __restrict__ post1) {
  __shared__ int count[TRELLIS_ALIGN_MAX_E];
  __shared__ int start[TRELLIS_ALIGN_MAX_E];
  __shared__ int fill[TRELLIS_ALIGN_MAX_E];
  __shared__ int total_c[2];
  using Scan = cub::BlockScan<int, 1024>;
  __shared__ typename Scan::TempStorage tmp;
  const int t = threadIdx.x;
  for (int e = t; e < num_experts; e += blockDim.x) { count[e] = 0; fill[e] = 0; }
  __syncthreads();
  for (int s = t; s < slots; s += blockDim.x) {
    int e = topk_ids[s];
    if (e >= 0 && e < num_experts) atomicAdd(&count[e], 1);
  }
  __syncthreads();
  for (int c = 0; c < num_classes; c++) {
    const int* map = c == 0 ? map0 : map1;
    const int block = c == 0 ? block0 : block1;
    int padded = 0;
    if (t < num_experts && map[t] >= 0) padded = ((count[t] + block - 1) / block) * block;
    int excl, total;
    Scan(tmp).ExclusiveSum(padded, excl, total);
    if (t < num_experts) start[t] = excl;
    if (t == 0) total_c[c] = total;
    __syncthreads();
    int* sorted = c == 0 ? sorted0 : sorted1;
    int* eids = c == 0 ? eids0 : eids1;
    const int cap = c == 0 ? cap0 : cap1;
    const int mblk = c == 0 ? mblk0 : mblk1;
    // expert ids per block (local ids), padding blocks -1
    if (t < num_experts && map[t] >= 0)
      for (int i = start[t]; i < start[t] + padded; i += block) eids[i / block] = map[t];
    for (int i = (total + block - 1) / block + t; i < mblk; i += blockDim.x) eids[i] = -1;
    // padding slots = numel (vLLM's sentinel); then the class's slots into their expert's range
    for (int i = total + t; i < cap; i += blockDim.x) sorted[i] = slots;
    for (int i = t; i < total; i += blockDim.x) sorted[i] = slots;   // pad the tails inside expert ranges too
    __syncthreads();
    for (int s = t; s < slots; s += blockDim.x) {
      int e = topk_ids[s];
      if (e >= 0 && e < num_experts && map[e] >= 0) {
        int pos = start[e] + atomicAdd(&fill[e], 1);
        sorted[pos] = s;
      }
    }
    if (t == 0) *(c == 0 ? post0 : post1) = total;
    __syncthreads();
  }
}

// topk_ids int32 [tokens, top_k] (global ids); maps: int32 [E] per class; outputs preallocated per class
void moe_align_decode(const at::Tensor& topk_ids, const std::vector<at::Tensor>& maps, const std::vector<int64_t>& blocks,
                      int64_t num_experts, const std::vector<at::Tensor>& sorted, const std::vector<at::Tensor>& eids,
                      const std::vector<at::Tensor>& post) {
  const at::cuda::OptionalCUDAGuard device_guard(topk_ids.device());
  const int nc = (int)maps.size();
  TORCH_CHECK(nc >= 1 && nc <= 2 && (int)blocks.size() == nc && (int)sorted.size() == nc && (int)eids.size() == nc && (int)post.size() == nc);
  TORCH_CHECK(topk_ids.dtype() == at::kInt && topk_ids.is_contiguous());
  const int slots = (int)topk_ids.numel();
  TORCH_CHECK(slots <= TRELLIS_ALIGN_MAX_SLOTS && num_experts <= TRELLIS_ALIGN_MAX_E, "moe_align_decode: decode sizes only");
  for (int c = 0; c < nc; c++) {
    TORCH_CHECK(maps[c].dtype() == at::kInt && maps[c].numel() == num_experts && maps[c].is_contiguous());
    TORCH_CHECK(sorted[c].dtype() == at::kInt && eids[c].dtype() == at::kInt && post[c].dtype() == at::kInt);
    TORCH_CHECK(eids[c].numel() * blocks[c] >= sorted[c].numel(), "expert_ids too short");
  }
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  auto P = [&](const std::vector<at::Tensor>& v, int c) { return c < nc ? v[c].data_ptr<int>() : nullptr; };
  auto M = [&](int c) { return c < nc ? maps[c].data_ptr<int>() : nullptr; };
  trellis_moe_align_decode_kernel<<<1, 1024, 0, stream>>>(
      topk_ids.data_ptr<int>(), slots, (int)num_experts, nc, M(0), M(1), (int)blocks[0], nc > 1 ? (int)blocks[1] : 1,
      P(sorted, 0), P(sorted, 1), (int)sorted[0].numel(), nc > 1 ? (int)sorted[1].numel() : 0,
      P(eids, 0), P(eids, 1), (int)eids[0].numel(), nc > 1 ? (int)eids[1].numel() : 0, P(post, 0), P(post, 1));
}

