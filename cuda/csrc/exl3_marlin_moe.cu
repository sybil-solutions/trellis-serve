// Grid-strided variants (prefill): instead of one 32-thread block per (row, 128-block) item - 4.2 M blocks per layer at
// 8k tokens - a FIXED grid of 256-thread blocks (8 warps each) strides over the items, as the dense template's
// cooperative prologue does. Warp g = blockIdx.x * 8 + threadIdx.x / 32 handles items g, g + G, g + 2G, ... (G = warps
// in the grid); all 32 lanes of a warp run the same trip count, so the warp shuffles inside the Hadamard stay in
// lockstep. Same statements per item as the kernels above => bit-identical results (checked by the parity tools).
// g_gs_blocks (knob moe_set_gridstride_blocks): -1 = automatic, 0 = always per-item launches (above), n > 0 = always n
// grid blocks. Automatic (grid-striding with enough blocks is faster at high token counts, worse with too few
// blocks): grid-strided with up to 8,448 blocks once there are at least
// 16,384 items (64 tokens here), per-item launches below that (decode sizes: no measurable difference).
static int g_gs_blocks = -1;
static constexpr int64_t kGsAutoMinItems = 16384;  // 64 tokens x top-8 x 2 slabs x 16 blocks
static constexpr int kGsAutoBlocks = 8448;

static int gs_blocks_for(int64_t items) {
  if (g_gs_blocks >= 0) return g_gs_blocks;
  return items >= kGsAutoMinItems ? kGsAutoBlocks : 0;
}

template <bool in_bf16, bool ids64>
__global__ __launch_bounds__(256)
void trellis_moe_had_in_gs_kernel(const half* __restrict__ x, half* __restrict__ xh, const half* __restrict__ suh,
                                 const void* __restrict__ ids, const int slots, const int top_k, const int shards,
                                 const int num_experts, const int kb, const int64_t* __restrict__ ptrs, const int pstride) {
  const size_t width = (size_t)kb * 128;
  const int64_t total = (int64_t)shards * slots * kb, stride = (int64_t)gridDim.x * 8;
  for (int64_t w = (int64_t)blockIdx.x * 8 + threadIdx.x / 32; w < total; w += stride) {
    const int blk = (int)(w % kb);
    const int64_t rs = w / kb;
    const int slot = (int)(rs % slots), shard = (int)(rs / slots);
    int64_t e = ids64 ? ((const int64_t*)ids)[slot] : (int64_t)((const int32_t*)ids)[slot];
    if (e < 0 || e >= num_experts) continue;  // dropped slot: write nothing
    const half* su = ptrs ? reinterpret_cast<const half*>(ptrs[e * pstride]) + width * shard : suh + width * (e * shards + shard);
    trellis_had_r_128_inner<in_bf16, false, true, false>(x + width * (slot / top_k) + blk * 128, xh + width * rs + blk * 128,
                                                        su, blk * 32, kHadScale);
  }
}

template <bool ids64>
__global__ __launch_bounds__(256)
void trellis_moe_glu_had_in_gs_kernel(const half* __restrict__ gu, half* __restrict__ xd, half* __restrict__ act_tmp,
                                     const half* __restrict__ suh, const void* __restrict__ ids, const int num_experts,
                                     const int slots, const int kb, const int64_t* __restrict__ ptrs, const int pstride) {
  const size_t inter = (size_t)kb * 128;
  const int64_t total = (int64_t)slots * kb, stride = (int64_t)gridDim.x * 8;
  const int t = threadIdx.x & 31;
  for (int64_t w = (int64_t)blockIdx.x * 8 + threadIdx.x / 32; w < total; w += stride) {
    const int blk = (int)(w % kb);
    const int64_t slot = w / kb;
    int64_t e = ids64 ? ((const int64_t*)ids)[slot] : (int64_t)((const int32_t*)ids)[slot];
    if (e < 0 || e >= num_experts) continue;  // dropped slot: write nothing
    const half4 g = ((const half4*)(gu + 2 * inter * slot + blk * 128))[t];
    const half4 u = ((const half4*)(gu + 2 * inter * slot + inter + blk * 128))[t];
    float2 g0 = __half22float2(g.x), g1 = __half22float2(g.y), u0 = __half22float2(u.x), u1 = __half22float2(u.y);
    half4 a;
    a.x = __floats2half2_rn(trellis_act_silu(g0.x) * u0.x, trellis_act_silu(g0.y) * u0.y);
    a.y = __floats2half2_rn(trellis_act_silu(g1.x) * u1.x, trellis_act_silu(g1.y) * u1.y);
    half* act = act_tmp + inter * slot + blk * 128;
    ((half4*)act)[t] = a;
    // No __syncthreads() here: it would synchronise the whole 256-thread block, and the 8 warps of a block have
    // different trip counts at the tail (hang). Each lane reads back only the vector it has just written itself.
    const half* su = ptrs ? reinterpret_cast<const half*>(ptrs[e * pstride]) : suh + inter * e;
    trellis_had_r_128_inner<false, false, true, false>(act, xd + inter * slot + blk * 128, su, blk * 32, kHadScale);
  }
}

// ---------------------------------------------------------------------------------------------------------------
// K08 compact variants for part-wise prefill: iterate only the slots listed in an align output (sorted ids of one expert
// part, entries < num_post that are < slots), instead of sweeping every slot of the chunk once per part. Same per-item
// arithmetic as the grid-strided kernels above -> bit-identical rows.
template <bool in_bf16, bool ids64>
__global__ __launch_bounds__(256)
void trellis_moe_had_in_compact_kernel(const half* __restrict__ x, half* __restrict__ xh, const void* __restrict__ ids,
                                       const int* __restrict__ sorted, const int* __restrict__ npost, const int cap,
                                       const int slots, const int top_k, const int shards, const int num_experts,
                                       const int kb, const int64_t* __restrict__ ptrs, const int pstride) {
  const size_t width = (size_t)kb * 128;
  const int n = min(*npost, cap);
  const int64_t total = (int64_t)shards * n * kb, stride = (int64_t)gridDim.x * 8;
  for (int64_t w = (int64_t)blockIdx.x * 8 + threadIdx.x / 32; w < total; w += stride) {
    const int blk = (int)(w % kb);
    const int64_t rs = w / kb;
    const int i = (int)(rs % n), shard = (int)(rs / n);
    const int slot = sorted[i];
    if (slot >= slots) continue;
    int64_t e = ids64 ? ((const int64_t*)ids)[slot] : (int64_t)((const int32_t*)ids)[slot];
    if (e < 0 || e >= num_experts) continue;
    const half* su = reinterpret_cast<const half*>(ptrs[e * pstride]) + width * shard;
    trellis_had_r_128_inner<in_bf16, false, true, false>(x + width * (slot / top_k) + blk * 128,
                                                        xh + width * ((int64_t)shard * slots + slot) + blk * 128, su,
                                                        blk * 32, kHadScale);
  }
}

template <bool ids64>
__global__ __launch_bounds__(256)
void trellis_moe_glu_had_in_compact_kernel(const half* __restrict__ gu, half* __restrict__ xd, half* __restrict__ act_tmp,
                                           const void* __restrict__ ids, const int* __restrict__ sorted,
                                           const int* __restrict__ npost, const int cap, const int slots,
                                           const int num_experts, const int kb, const int64_t* __restrict__ ptrs,
                                           const int pstride) {
  const size_t inter = (size_t)kb * 128;
  const int n = min(*npost, cap);
  const int64_t total = (int64_t)n * kb, stride = (int64_t)gridDim.x * 8;
  const int t = threadIdx.x & 31;
  for (int64_t w = (int64_t)blockIdx.x * 8 + threadIdx.x / 32; w < total; w += stride) {
    const int blk = (int)(w % kb);
    const int slot = sorted[w / kb];
    if (slot >= slots) continue;
    int64_t e = ids64 ? ((const int64_t*)ids)[slot] : (int64_t)((const int32_t*)ids)[slot];
    if (e < 0 || e >= num_experts) continue;
    const half4 g = ((const half4*)(gu + 2 * inter * slot + blk * 128))[t];
    const half4 u = ((const half4*)(gu + 2 * inter * slot + inter + blk * 128))[t];
    float2 g0 = __half22float2(g.x), g1 = __half22float2(g.y), u0 = __half22float2(u.x), u1 = __half22float2(u.y);
    half4 a;
    a.x = __floats2half2_rn(trellis_act_silu(g0.x) * u0.x, trellis_act_silu(g0.y) * u0.y);
    a.y = __floats2half2_rn(trellis_act_silu(g1.x) * u1.x, trellis_act_silu(g1.y) * u1.y);
    half* act = act_tmp + inter * slot + blk * 128;
    ((half4*)act)[t] = a;
    const half* su = reinterpret_cast<const half*>(ptrs[e * pstride]);
    trellis_had_r_128_inner<false, false, true, false>(act, xd + inter * slot + blk * 128, su, blk * 32, kHadScale);
  }
}

