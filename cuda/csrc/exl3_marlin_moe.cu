  else if (i64)   trellis_moe_combine_kernel<false, true><<<grid, 32, 0, stream>>>(ydp, wp, yp, ids.data_ptr(), (int)top_k, (int)num_experts);
  else            trellis_moe_combine_kernel<false, false><<<grid, 32, 0, stream>>>(ydp, wp, yp, ids.data_ptr(), (int)top_k, (int)num_experts);
  // clang-format on
}

