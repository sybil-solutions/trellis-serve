// Grouped GEMM with B (and svh, field_s >= 0) from the pointer table. a fp16 [shards * rows, k], c fp16 [rows, n];
// bits = EXL3 K of every expert (2, 3 or 4); B layout per expert: [k/16, n/64, 4, 8K] int32 (K=2, 3) / [k/16, n/64, 32, 4] (K=4).
void moe_gemm_ptr(const at::Tensor& a, at::Tensor& c, const at::Tensor& ptrs, int64_t field_b, int64_t field_s,
                  int64_t bits, const at::Tensor& sorted_ids, const at::Tensor& expert_ids,
                  const at::Tensor& num_post_padded, int64_t moe_block_size, int64_t shard_end, int64_t cb,
                  int64_t thread_k, int64_t thread_n, int64_t scratch, const c10::optional<at::Tensor>& wb) {
  const at::cuda::OptionalCUDAGuard device_guard(a.device());
  TORCH_CHECK(a.dim() == 2 && c.dim() == 2 && a.dtype() == at::kHalf && c.dtype() == at::kHalf);
  TORCH_CHECK(a.is_contiguous() && c.is_contiguous());
  check_ptrs(ptrs, field_b);
  const int64_t* wb_ptr = nullptr;
  if (wb.has_value()) {
    check_ptrs(*wb, field_b);
    TORCH_CHECK(wb->sizes() == ptrs.sizes(), "wb table must have the table's shape");
    wb_ptr = wb->data_ptr<int64_t>() + field_b;
  }
  TORCH_CHECK(field_s < ptrs.size(1));
  TORCH_CHECK(bits == 2 || bits == 3 || bits == 4, "pointer-table GEMM: K = 2, 3 or 4");
  const int64_t rows = c.size(0), k = a.size(1), n = c.size(1), shards = shard_end > 0 ? 2 : 1;
  TORCH_CHECK(a.size(0) == shards * rows, "a must be [shards * rows, k]");
  TORCH_CHECK(k % 128 == 0 && n % 128 == 0);
  TORCH_CHECK(moe_block_size == 8 || (moe_block_size % 16 == 0 && moe_block_size >= 16 && moe_block_size <= 64),
              "unsupported moe_block_size ", moe_block_size);
  TORCH_CHECK(sorted_ids.dtype() == at::kInt && expert_ids.dtype() == at::kInt && num_post_padded.dtype() == at::kInt);
  TORCH_CHECK(sorted_ids.is_contiguous() && expert_ids.is_contiguous() && num_post_padded.numel() == 1);
  TORCH_CHECK(expert_ids.numel() >= sorted_ids.numel() / moe_block_size, "expert_ids too short");
  TORCH_CHECK(shard_end >= 0 && shard_end < n && shard_end % 128 == 0);
  TORCH_CHECK((int64_t)shards * rows * (k / 8) < INT_MAX, "input slabs exceed the kernel's 32-bit offsets");
  TORCH_CHECK(scratch == 0 || scratch == 1, "scratch must be 0 or 1");
  if (rows == 0) return;
  const int64_t* tb = ptrs.data_ptr<int64_t>();
  // B / svh arguments must be non-null for the launcher's config logic (svh != nullptr = output transform);
  // the kernel replaces them from the table before any use.
  const half* svh_dummy = field_s >= 0 ? (const half*)c.data_ptr() : nullptr;
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  trellis_exl3_marlin_moe::gemm_launch((const half*)a.data_ptr(), (const int*)a.data_ptr(), (half*)c.data_ptr(), svh_dummy,
                                      (const int*)sorted_ids.data_ptr(), (const int*)expert_ids.data_ptr(),
                                      (const int*)num_post_padded.data_ptr(), (int)moe_block_size, (int)rows, (int)n,
                                      (int)k, (int)shard_end, (int)cb, (int)bits, a.get_device(), stream, (int)thread_k,
                                      (int)thread_n, (int)scratch, tb + field_b, field_s >= 0 ? tb + field_s : nullptr,
                                      (int)ptrs.size(1), (int)ptrs.size(0), wb_ptr);
}

// Fused admission, small fields: for every routed slot with a valid id e and dst[e, field] != 0, copy nbytes
// (multiple of 16) from src[e, field] to dst[e, field]. Duplicate ids copy the same bytes twice (benign).
__global__ void trellis_moe_copy_fields_kernel(const int64_t* __restrict__ src, const int64_t* __restrict__ dst,
                                               const void* __restrict__ ids, bool ids64, int stride, int rows,
                                               int field, int n16) {
  const int slot = blockIdx.x;
  const int64_t e = ids64 ? ((const int64_t*)ids)[slot] : (int64_t)((const int32_t*)ids)[slot];
  if (e < 0 || e >= rows) return;
  int4* d = reinterpret_cast<int4*>(dst[e * stride + field]);
  if (d == nullptr) return;
  const int4* s = reinterpret_cast<const int4*>(src[e * stride + field]);
  // K07: one 16-B (zero-copy) load per thread (grid.y chunks of 256 x 16 B per slot): all loads of a slot are in flight
  // at once instead of ~5 dependent PCIe round trips per thread
  const int i = blockIdx.y * blockDim.x + threadIdx.x;
  if (i < n16) d[i] = s[i];
}

void moe_copy_fields(const at::Tensor& src, const at::Tensor& dst, const at::Tensor& ids, int64_t field, int64_t nbytes) {
  const at::cuda::OptionalCUDAGuard device_guard(src.device());
  check_ptrs(src, field);
  check_ptrs(dst, field);
  TORCH_CHECK(src.sizes() == dst.sizes() && is_index(ids) && ids.is_contiguous() && nbytes % 16 == 0 && nbytes > 0);
  if (ids.numel() == 0) return;
  dim3 grid((unsigned)ids.numel(), (unsigned)((nbytes / 16 + 255) / 256));
  trellis_moe_copy_fields_kernel<<<grid, 256, 0, at::cuda::getCurrentCUDAStream().stream()>>>(
      src.data_ptr<int64_t>(), dst.data_ptr<int64_t>(), ids.data_ptr(), ids.dtype() == at::kLong, (int)src.size(1),
      (int)src.size(0), (int)field, (int)(nbytes / 16));
}

// Record copy (copy-in / prefetch / eviction), graph-safe: entry i < *count (count = nullptr: all n entries) copies
// nbytes from src[i] to dst[i] (absolute addresses; 0 = skip). grid (chunks, n): block (c, i) copies chunk c of entry
// i with 16-byte loads, UNROLL loads in flight per thread before the stores (PCIe reads need many requests in flight).
template <int UNROLL>
__global__ __launch_bounds__(256) void trellis_copy_records_kernel(const int64_t* __restrict__ src,
                                                                   const int64_t* __restrict__ dst,
                                                                   const int* __restrict__ count, int64_t n16,
                                                                   int64_t chunk16) {
  const int i = blockIdx.y;
  if (count != nullptr && i >= *count) return;
  const int4* s = reinterpret_cast<const int4*>(src[i]);
  int4* d = reinterpret_cast<int4*>(dst[i]);
  if (s == nullptr || d == nullptr) return;
  const int64_t beg = (int64_t)blockIdx.x * chunk16, end = min(beg + chunk16, n16);
  for (int64_t base = beg + threadIdx.x; base < end; base += 256 * UNROLL) {
    int4 v[UNROLL];
  #pragma unroll
    for (int u = 0; u < UNROLL; u++) {
      const int64_t j = base + u * 256;
      if (j < end) v[u] = __ldg(s + j);
    }
  #pragma unroll
    for (int u = 0; u < UNROLL; u++) {
      const int64_t j = base + u * 256;
      if (j < end) d[j] = v[u];
    }
  }
}

// Small-footprint variant: `blocks` persistent 512-thread blocks grid-stride over all (entry, 8 KB piece) items with 8
// x 16-B loads in flight per thread (64 KB per block): a prefetch that leaves the other SMs to concurrent kernels.
__global__ __launch_bounds__(512) void trellis_copy_records_persistent_kernel(const int64_t* __restrict__ src,
                                                                              const int64_t* __restrict__ dst,
                                                                              const int* __restrict__ count, int n,
                                                                              int64_t n16) {
  const int cnt = count != nullptr ? min(*count, n) : n;
  constexpr int kPiece16 = 512 * 8;  // one piece = 64 KB = one pass of the block
  const int64_t pieces = (n16 + kPiece16 - 1) / kPiece16, total = (int64_t)cnt * pieces;
  for (int64_t it = blockIdx.x; it < total; it += gridDim.x) {
    const int i = (int)(it / pieces);
    const int4* s = reinterpret_cast<const int4*>(src[i]);
    int4* d = reinterpret_cast<int4*>(dst[i]);
    if (s == nullptr || d == nullptr) continue;
    const int64_t beg = (it % pieces) * kPiece16;
    int4 v[8];
  #pragma unroll
    for (int u = 0; u < 8; u++) {
      const int64_t j = beg + u * 512 + threadIdx.x;
      if (j < n16) v[u] = __ldg(s + j);
    }
  #pragma unroll
    for (int u = 0; u < 8; u++) {
      const int64_t j = beg + u * 512 + threadIdx.x;
      if (j < n16) d[j] = v[u];
    }
  }
}

static int g_copy_chunk_kb = 64;  // knob: bytes per block (KB)

void copy_records(const at::Tensor& src, const at::Tensor& dst, int64_t nbytes, const c10::optional<at::Tensor>& count,
                  int64_t unroll) {
  const at::cuda::OptionalCUDAGuard device_guard(src.device());
  TORCH_CHECK(src.is_cuda() && dst.is_cuda() && src.dtype() == at::kLong && dst.dtype() == at::kLong);
  TORCH_CHECK(src.is_contiguous() && dst.is_contiguous() && src.numel() == dst.numel() && nbytes % 16 == 0);
  const int* cp = nullptr;
  if (count.has_value()) {
    TORCH_CHECK(count->is_cuda() && count->dtype() == at::kInt && count->numel() == 1);
    cp = count->data_ptr<int>();
  }
  const int64_t n = src.numel();
  if (n == 0 || nbytes == 0) return;
  const int64_t n16 = nbytes / 16, chunk16 = (int64_t)g_copy_chunk_kb * 1024 / 16;
  dim3 grid((unsigned)((n16 + chunk16 - 1) / chunk16), (unsigned)n);
  cudaStream_t stream = at::cuda::getCurrentCUDAStream().stream();
  const int64_t* sp = src.data_ptr<int64_t>(); const int64_t* dp = dst.data_ptr<int64_t>();
  if (unroll == 1) trellis_copy_records_kernel<1><<<grid, 256, 0, stream>>>(sp, dp, cp, n16, chunk16);
  else if (unroll == 2) trellis_copy_records_kernel<2><<<grid, 256, 0, stream>>>(sp, dp, cp, n16, chunk16);
  else if (unroll == 8) trellis_copy_records_kernel<8><<<grid, 256, 0, stream>>>(sp, dp, cp, n16, chunk16);
  else trellis_copy_records_kernel<4><<<grid, 256, 0, stream>>>(sp, dp, cp, n16, chunk16);
}

void copy_records_persistent(const at::Tensor& src, const at::Tensor& dst, int64_t nbytes,
                             const c10::optional<at::Tensor>& count, int64_t blocks) {
  const at::cuda::OptionalCUDAGuard device_guard(src.device());
  TORCH_CHECK(src.is_cuda() && dst.is_cuda() && src.dtype() == at::kLong && dst.dtype() == at::kLong);
  TORCH_CHECK(src.is_contiguous() && dst.is_contiguous() && src.numel() == dst.numel() && nbytes % 16 == 0);
  TORCH_CHECK(blocks >= 1 && blocks <= 4096);
  const int* cp = nullptr;
  if (count.has_value()) {
    TORCH_CHECK(count->is_cuda() && count->dtype() == at::kInt && count->numel() == 1);
    cp = count->data_ptr<int>();
  }
  if (src.numel() == 0 || nbytes == 0) return;
  trellis_copy_records_persistent_kernel<<<(unsigned)blocks, 512, 0, at::cuda::getCurrentCUDAStream().stream()>>>(
      src.data_ptr<int64_t>(), dst.data_ptr<int64_t>(), cp, (int)src.numel(), nbytes / 16);
}

